export function findRecipeByIndexTitle(title: string): StandardizedRecipe | undefined {
  const q = title.trim().toLowerCase();
  if (!q) return undefined;
  return (
    STANDARDIZED_RECIPES.find((r) => r.title.toLowerCase() === q) ||
    STANDARDIZED_RECIPES.find((r) => r.searchAliases?.some((a) => a.toLowerCase() === q)) ||
    STANDARDIZED_RECIPES.find((r) => r.title.toLowerCase().startsWith(`${q} (`)) ||
    STANDARDIZED_RECIPES.find((r) => r.title.toLowerCase().includes(q))
  );
}

