export function localizeRecipeDetail(
  recipe: StandardizedRecipe,
  lang: AppLanguage
): CoreRecipeArDetail {
  if (lang === 'ar') {
    return CORE_RECIPE_DETAILS_AR[recipe.id] || {};
  }
  if (lang === 'am') {
    if (CORE_RECIPE_DETAILS_AM[recipe.id]) {
      return CORE_RECIPE_DETAILS_AM[recipe.id];
    }
    return {
      steps: recipe.steps.map(translateRecipeStepToAm),
      qualityStandard: recipe.qualityStandard
        ? translateQualityStandardToAm(recipe.qualityStandard)
        : undefined,
      storage: localizeStorageAm(recipe.storage),
    };
  }
  return {};
}
