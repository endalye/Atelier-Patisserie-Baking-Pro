export function getLocalizedTocEntry(entry: TocEntry, lang: AppLanguage): TocEntry {
  if (lang === 'ar' && TOC_ENTRIES_AR[entry.id]) {
    return {
      ...entry,
      ...TOC_ENTRIES_AR[entry.id],
    };
  }
  if (lang === 'am' && TOC_ENTRIES_AM[entry.id]) {
    return {
      ...entry,
      ...TOC_ENTRIES_AM[entry.id],
    };
  }
  return entry;
}

export function getLocalizedManualPart(part: ManualPart, lang: AppLanguage): ManualPart {
  if (lang === 'en') return part;
  const localizedPart = lang === 'ar' ? MANUAL_PARTS_AR[part.id] : MANUAL_PARTS_AM[part.id];
  if (!localizedPart) return part;
  return {
    ...part,
    label: localizedPart.label,
    title: localizedPart.title,
    summary: localizedPart.summary,
    blocks: part.blocks.map((block, idx) => {
      const override = localizedPart.blocks[idx];
      if (!override) return block;
      return {
        ...block,
        ...override,
      };
    }),
  };
}
